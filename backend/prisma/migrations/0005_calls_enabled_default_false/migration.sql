-- SAF-244 (Legal-ревью, F1): убираем fail-open default на уровне БД.
-- DEFAULT true позволял вставке пользователя в обход verify-code (скрипт,
-- ручная правка, будущий код) молча включить вызовы без согласия —
-- для нормы, где бремя доказывания лежит на нас (ч. 1 ст. 44.1-1 126-ФЗ,
-- ч. 3 ст. 9 152-ФЗ), это генератор нарушений. Согласие включается только
-- активным действием абонента (запись grant в call_consents той же
-- транзакцией); default false — fail-closed для любого пути создания.
ALTER TABLE "users" ALTER COLUMN "callsEnabled" SET DEFAULT false;
